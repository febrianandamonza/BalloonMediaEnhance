/* =====================================================================
   DWIBAHASA — Bahasa Indonesia & English
   ---------------------------------------------------------------------
   Kamus di bawah memakai kalimat bahasa Indonesia sebagai kunci. Pilihan
   ini disengaja:

     · Bahasa Indonesia tetap menjadi bahasa sumber di dalam kode,
       sehingga berkas komponen tetap terbaca apa adanya.
     · Hanya sisi Inggris yang perlu ditulis; tidak ada kunci buatan
       seperti "settings.gimbal.title" yang harus dihafal.
     · Data yang didefinisikan di lingkup modul (daftar templat, kelas
       objek, baris tabel) cukup ditulis sekali dalam bahasa Indonesia,
       lalu diterjemahkan di tempat ia ditampilkan.

   Seluruh terjemahan tersimpan di dalam berkas program ini — tidak ada
   permintaan jaringan, tidak ada berkas bahasa terpisah yang perlu
   diunduh. Pilihan bahasa disimpan di penyimpanan peramban.

   Istilah yang dibiarkan sama pada kedua bahasa: nama modul dan produk
   (Mission Dashboard, Crowd Counting, GeoInt Visualisation), nama
   perangkat (Epsilon, FLIR Tau 2), serta singkatan teknis baku (RTSP,
   CUDA, WGS-84). Menerjemahkannya justru menyulitkan operator.
   ===================================================================== */

export type Lang = 'id' | 'en';

export const LANGUAGES: { id: Lang; label: string; native: string }[] = [
  { id: 'id', label: 'Indonesian', native: 'Bahasa Indonesia' },
  { id: 'en', label: 'English', native: 'English' },
];

/* Kunci v2: pilihan lama ('skystar.lang', bawaan 'id') sengaja diabaikan
   agar semua operator mulai dari English. Bahasa awal tidak mengikuti
   bahasa sistem/peramban — selalu English sampai operator memilih lain. */
const STORAGE_KEY = 'skystar.lang.v2';
export const DEFAULT_LANG: Lang = 'en';

export function loadLang(): Lang {
  if (typeof window === 'undefined') return DEFAULT_LANG;
  try {
    const v = window.localStorage.getItem(STORAGE_KEY);
    return v === 'en' || v === 'id' ? v : DEFAULT_LANG;
  } catch {
    return DEFAULT_LANG;
  }
}

export function saveLang(lang: Lang) {
  try { window.localStorage.setItem(STORAGE_KEY, lang); } catch { /* noop */ }
}

